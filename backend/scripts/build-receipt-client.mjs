// Bundles src/receipts/client/main.ts (viem keys + qrcode-generator + the
// shared sid derivation) into src/receipts/client.generated.ts, served by the
// Worker at /potvrda/client.js. Run after changing the client:
//   npm run build:receipt-client
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const res = await build({
  entryPoints: [join(here, '../src/receipts/client/main.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  legalComments: 'none',
});
const js = res.outputFiles[0].text;
writeFileSync(
  join(here, '../src/receipts/client.generated.ts'),
  '// GENERATED by scripts/build-receipt-client.mjs — do not edit.\n' +
    `export const RECEIPT_CLIENT_JS = ${JSON.stringify(js)};\n`,
);
console.log(`receipt client: ${(js.length / 1024).toFixed(1)} KiB`);
