// Bundles src/receipts/client/main.ts (viem keys + qrcode-generator + the
// shared sid derivation) into src/receipts/client.generated.ts, served by the
// Worker at /potvrda/client.js. Run after changing the client:
//   npm run build:receipt-client
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const bundle = async (entry) => {
  const res = await build({
    entryPoints: [join(here, '../src/receipts/client', entry)],
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'es2020',
    write: false,
    legalComments: 'none',
    loader: { '.ttf': 'binary' },
  });
  return res.outputFiles[0].text;
};
// main: keys, sid, signing, rendering. pdf: pdf-lib + fontkit + Inter, loaded
// with the page so building the PDF later needs no network (no print dialog).
const js = await bundle('main.ts');
const pdf = await bundle('pdf-entry.ts');
writeFileSync(
  join(here, '../src/receipts/client.generated.ts'),
  '// GENERATED by scripts/build-receipt-client.mjs — do not edit.\n' +
    `export const RECEIPT_CLIENT_JS = ${JSON.stringify(js)};\n` +
    `export const RECEIPT_PDF_JS = ${JSON.stringify(pdf)};\n`,
);
console.log(`receipt client: ${(js.length / 1024).toFixed(1)} KiB, pdf: ${(pdf.length / 1024).toFixed(1)} KiB`);
