// Bundles src/setup/client/main.ts (viem + the shared safe-tx/lib builders)
// into src/setup/client.generated.ts, served by the Worker at
// /admin/setup/client.js (ADR 0027). Run after changing the client or
// safe-tx/lib:
//   npm run build:setup-client
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const res = await build({
  entryPoints: [join(here, '../src/setup/client/main.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  legalComments: 'none',
});
const js = res.outputFiles[0].text;
writeFileSync(
  join(here, '../src/setup/client.generated.ts'),
  '// GENERATED by scripts/build-setup-client.mjs — do not edit.\n' +
    `export const SETUP_CLIENT_JS = ${JSON.stringify(js)};\n`,
);
console.log(`setup client: ${(js.length / 1024).toFixed(1)} KiB`);
